from __future__ import annotations

import random
from typing import Any


def pick(pool: list[str]) -> str:
    return random.choice(pool)


def maybe_suffix(pool: list[str], chance: float = 0.48) -> str:
    if random.random() > chance:
        return ""
    return pick(pool)


